def get_dungeon_monster(floor):
    if floor % 5 == 0:
        boss_idx = min((floor // 5) - 1, len(DUNGEON_BOSSES) - 1)
        boss = DUNGEON_BOSSES[boss_idx].copy()
        boss["hp"] += (floor - 5) * 2
        boss["attack"] += (floor - 5) // 2
        boss["defense"] += (floor - 5) // 4
        boss["is_boss"] = True
        return boss
    else:
        idx = min((floor - 1) // 3, len(DUNGEON_MONSTERS) - 1)
        monster = DUNGEON_MONSTERS[idx].copy()
        monster["hp"] += (floor - 1) * 2
        monster["attack"] += (floor - 1) // 2
        monster["defense"] += (floor - 1) // 4
        monster["is_boss"] = False
        return monster

def get_random_event():
    total_weight = sum(e["weight"] for e in DUNGEON_EVENTS)
    roll = random.randint(1, total_weight)
    cumulative = 0
    for event in DUNGEON_EVENTS:
        cumulative += event["weight"]
        if roll <= cumulative:
            return event["type"]
    return "combat"